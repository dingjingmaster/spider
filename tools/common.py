__all__ = ["traditional_to_simplified"]


def traditional_to_simplified(text):
    """把字符串中的繁体字转换为简体字。

    没有需要转换的字符时返回原对象；非字符串输入原样返回。
    """
    if not isinstance(text, str):
        return text
    converted = text.translate(_T2S_TABLE)
    return text if converted == text else converted
